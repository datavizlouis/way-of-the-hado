#!/usr/bin/env python3
"""Turn the VGM rips in app/assets/music/ into the WAVs the site plays.

  app/assets/music/<name>.vgz  ->  app/assets/audio/<id>.wav      (both git-ignored: Capcom music)
                               ->  app/src/lib/trackLoops.js      (loop points only, committed)

The fighter tracks need a QSound emulator and opening / player_select need YM2151 + OKIM6295,
which ffmpeg's libgme can't play, so the rendering is done by VGMPlay
(https://github.com/vgmrips/vgmplay-legacy, 0.40.9). Each track is rendered once through,
with no fade: the player seeks back to the loop point itself.

usage: convert_music.py --loops-only        just write trackLoops.js from the VGZ headers
       convert_music.py VGMPLAY_DIR         also render the WAVs (edits VGMPlay.ini in that folder)
       convert_music.py --mp3               encode the rendered WAVs to MP3 with ffmpeg. The build
                                            ships a track's MP3 instead of its WAV when both exist.
                                            Constant bitrate, so seeking to a loop point is accurate.
"""
import gzip
import json
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MUSIC = ROOT / 'app' / 'assets' / 'music'
AUDIO = ROOT / 'app' / 'assets' / 'audio'
LOOPS = ROOT / 'app' / 'src' / 'lib' / 'trackLoops.js'
# the rips' file names, where they differ from the Id column of data/characters.csv
IDS = {'ehonda': 'honda', 'mbison': 'bison'}
VGM_RATE = 44100
MP3_BITRATE = '192k'


def header(path):
    d = gzip.open(path).read()
    total, loop_offset, loop_samples = struct.unpack_from('<I', d, 0x18)[0], struct.unpack_from('<I', d, 0x1C)[0], struct.unpack_from('<I', d, 0x20)[0]
    return {'total': total, 'loop_start': total - loop_samples if loop_offset and loop_samples else 0}


def write_loops(tracks):
    data = {IDS.get(p.stem, p.stem): round(h['loop_start'] / VGM_RATE, 4) for p, h in tracks}
    LOOPS.write_text(
        '// Generated by scripts/convert_music.py. Where each track loops back to, in seconds:\n'
        '// the part before it is an intro that plays once. 0 = loop the whole track.\n'
        f'export const TRACK_LOOPS = {json.dumps(data, indent=2, sort_keys=True)};\n',
        encoding='utf8',
    )
    print(f'{LOOPS.name}: {len(data)} tracks')


def configure(ini):
    s = ini.read_text(encoding='latin-1')
    for pattern, value in [
        (r'(?m)^SampleRate = \d+', f'SampleRate = {VGM_RATE}'),
        (r'(?m)^FadeTime = \d+', 'FadeTime = 0'),
        (r'(?m)^LogSound = \d', 'LogSound = 1'),  # log only, no audio device
        (r'(?m)^MaxLoops = 0x\d+', 'MaxLoops = 0x01'),
    ]:
        s, n = re.subn(pattern, value, s)
        if n != 1:
            raise SystemExit(f'VGMPlay.ini: expected one match for {pattern}, found {n}')
    ini.write_text(s, encoding='latin-1')


def render(exe, path, h):
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / path.name
        shutil.copy(path, work)
        subprocess.run([str(exe), work.name], cwd=tmp, stdin=subprocess.DEVNULL, check=True, timeout=600)
        out = work.with_suffix('.wav')
        if not out.exists():
            raise SystemExit(f'VGMPlay wrote no WAV for {path.name}: {[p.name for p in Path(tmp).iterdir()]}')
        with wave.open(str(out)) as w:
            secs = w.getnframes() / w.getframerate()
        want = h['total'] / VGM_RATE
        if abs(secs - want) > 0.5:
            raise SystemExit(f'{path.name}: rendered {secs:.1f}s, the VGM header says {want:.1f}s')
        dest = AUDIO / f'{IDS.get(path.stem, path.stem)}.wav'
        shutil.move(str(out), dest)
        print(f'{dest.name}: {secs:.1f}s, {dest.stat().st_size / 1e6:.1f} MB')


def encode_mp3():
    wavs = sorted(AUDIO.glob('*.wav'))
    if not wavs:
        raise SystemExit(f'no .wav files in {AUDIO}: render them first')
    for wav in wavs:
        mp3 = wav.with_suffix('.mp3')
        subprocess.run(
            ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(wav), '-c:a', 'libmp3lame', '-b:a', MP3_BITRATE, str(mp3)],
            check=True,
        )
        print(f'{mp3.name}: {mp3.stat().st_size / 1e6:.1f} MB')


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    if sys.argv[1] == '--mp3':
        return encode_mp3()
    tracks = [(p, header(p)) for p in sorted(MUSIC.glob('*.vgz'))]
    if not tracks:
        raise SystemExit(f'no .vgz files in {MUSIC}')
    write_loops(tracks)
    if sys.argv[1] == '--loops-only':
        return
    folder = Path(sys.argv[1])
    configure(folder / 'VGMPlay.ini')
    AUDIO.mkdir(parents=True, exist_ok=True)
    for path, h in tracks:
        render((folder / 'VGMPlay.exe').resolve(), path, h)


if __name__ == '__main__':
    main()
