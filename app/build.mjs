// Build the React/Three app into the Tableau extension package.
//
//   node build.mjs          -> production bundle into tableau/Packages/<id>/content/
//   node build.mjs --dev    -> local preview in app/dev-out/ with a mock Extensions API
//                              backed by ../data/*.csv (serve with: npx esbuild --servedir=dev-out)
//
// Assets in app/assets/ (all optional):
//   img/**, sprites/*.png, fonts/*  -> inlined as data URIs into hado-assets.js
//   sprites/sprites.json            -> sprite sheet frame definitions
//   audio/<id>.mp3|ogg|m4a          -> copied next to the bundle, played via <audio>

import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dev = process.argv.includes('--dev');
const PKG = path.join(here, '..', 'tableau', 'Packages', 'com.tableau.mcp.way-of-the-hado', 'content');
const OUT = dev ? path.join(here, 'dev-out') : PKG;
const ASSETS = path.join(here, 'assets');

const MIME = {
  '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.gif': 'image/gif', '.svg': 'image/svg+xml',
  '.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf', '.otf': 'font/otf',
};
const FONT_FAMILIES = { brush: 'HadoBrush', display: 'HadoDisplay', pixel: 'HadoPixel' };
// Restrict a family to the glyphs it really has. The personal-use build of Cafe Felix
// (brush) maps digits and punctuation to a watermark, so only A-Z/a-z/space use it and
// everything else falls through to the next font in the stack.
const FONT_RANGES = { HadoBrush: 'U+0020,U+0041-005A,U+0061-007A' };

function walk(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.name.startsWith('.') || e.name === 'raw') return []; // raw/ = unsliced source sheets
    return e.isDirectory() ? walk(p, base) : [path.relative(base, p).split(path.sep).join('/')];
  });
}

function buildAssets() {
  const files = {};
  const audio = {};
  const fontFaces = [];
  let bytes = 0;
  for (const rel of walk(ASSETS)) {
    const ext = path.extname(rel).toLowerCase();
    const abs = path.join(ASSETS, rel);
    if (rel.startsWith('audio/')) {
      if (!['.mp3', '.ogg', '.m4a', '.wav'].includes(ext)) continue;
      const id = path.basename(rel, ext);
      const dest = path.join(OUT, 'assets', 'audio', path.basename(rel));
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(abs, dest);
      audio[id] = `assets/audio/${path.basename(rel)}`;
      continue;
    }
    if (!MIME[ext]) continue;
    const buf = fs.readFileSync(abs);
    bytes += buf.length;
    const uri = `data:${MIME[ext]};base64,${buf.toString('base64')}`;
    if (rel.startsWith('fonts/')) {
      const fam = FONT_FAMILIES[path.basename(rel, ext).toLowerCase()];
      const range = FONT_RANGES[fam] ? `unicode-range:${FONT_RANGES[fam]};` : '';
      if (fam) fontFaces.push(`@font-face{font-family:'${fam}';src:url(${uri});font-display:swap;${range}}`);
      continue;
    }
    files[rel] = uri;
  }
  let sprites = {};
  const sj = path.join(ASSETS, 'sprites', 'sprites.json');
  if (fs.existsSync(sj)) {
    sprites = JSON.parse(fs.readFileSync(sj, 'utf8'));
    delete sprites._example;
  }
  const js =
    `window.HADO_ASSETS=${JSON.stringify({ files, audio, sprites })};\n` +
    (fontFaces.length
      ? `(function(){var s=document.createElement('style');s.textContent=${JSON.stringify(fontFaces.join('\n'))};document.head.appendChild(s);})();\n`
      : '');
  fs.mkdirSync(path.join(OUT, 'src'), { recursive: true });
  fs.writeFileSync(path.join(OUT, 'src', 'hado-assets.js'), js);
  console.log(
    `assets: ${Object.keys(files).length} images, ${fontFaces.length} fonts, ${Object.keys(sprites).length} sprite sheets, ${Object.keys(audio).length} audio (${(bytes / 1024).toFixed(0)} KB inlined)`,
  );
}

function html(extra = '') {
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Way of the Hado</title>
    <link rel="stylesheet" href="src/styles.css" />
  </head>
  <body>
    <div id="app"></div>
    <!-- Tableau Extensions API library. Must load before app.js. -->
    <script src="src/tableau.extensions.1.latest.min.js"></script>
    <!-- Generated by build.mjs: optional user assets inlined as data URIs. -->
    <script src="src/hado-assets.js"></script>${extra}
    <script src="src/app.js"></script>
  </body>
</html>
`;
}

fs.mkdirSync(path.join(OUT, 'src'), { recursive: true });
// drop stale audio from earlier builds
fs.rmSync(path.join(OUT, 'assets'), { recursive: true, force: true });
buildAssets();

await esbuild.build({
  entryPoints: [path.join(here, 'src', 'main.jsx')],
  bundle: true,
  format: 'iife',
  minify: !dev,
  sourcemap: dev ? 'inline' : false,
  target: ['es2019'],
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': dev ? '"development"' : '"production"' },
  outfile: path.join(OUT, 'src', 'app.js'),
  legalComments: 'none',
  logLevel: 'info',
});
fs.copyFileSync(path.join(here, 'src', 'styles.css'), path.join(OUT, 'src', 'styles.css'));

if (dev) {
  // mock Extensions API fed by the CSVs
  const dataDir = path.join(here, '..', 'data');
  const csvs = {
    Story: fs.readFileSync(path.join(dataDir, 'story.csv'), 'utf8'),
    Characters: fs.readFileSync(path.join(dataDir, 'characters.csv'), 'utf8'),
    'Franchise Metrics': fs.readFileSync(path.join(dataDir, 'franchise_metrics.csv'), 'utf8'),
  };
  const mock = fs.readFileSync(path.join(here, 'dev', 'mock-tableau.js'), 'utf8');
  fs.writeFileSync(path.join(OUT, 'src', 'tableau.extensions.1.latest.min.js'), `window.__CSV__=${JSON.stringify(csvs)};\n${mock}`);
  fs.writeFileSync(path.join(OUT, 'index.html'), html());
  console.log(`dev build -> ${OUT}`);
} else {
  fs.writeFileSync(path.join(OUT, 'index.html'), html());
  console.log(`production build -> ${OUT}`);
}
